def gen() -> list[dict]:
    rows: list[dict] = []
    for title, desc, steps, deadlines in SCENARIOS:
        # Для каждого сценария делаем несколько вариаций с разным уровнем срочности
        for level in ("urgent", "high", "medium"):
            for _ in range(3):  # 3 вариации на уровень
                deadline = random.choice(deadlines)
                base_input = random.choice([
                    desc.lower(),
                    title.lower(),
                    f"нужно {desc.lower()}",
                    f"надо {title.lower()}",
                ])
                inp = _maybe_prefix(base_input, level)
                # Срок иногда упоминаем во входе
                if random.random() < 0.5:
                    inp = f"{inp}, срок {deadline}" if deadline != "без срока" else inp

                # priority: urgent если есть слово срочности, иначе high/medium
                priority = level if level != "medium" else random.choice(["medium", "high"])

                # Чекпоинты: подставляем under-deadlines как есть (они уже осмысленны)
                cps = []
                for s, sub in steps:
                    cps.append({"step": s, "deadline": sub})
                # последний шаг получает общий дедлайн, если у него нет своего
                if cps and cps[-1]["deadline"] is None and deadline != "без срока":
                    cps[-1]["deadline"] = deadline

                rows.append({
                    "input": inp,
                    "output": {
                        "title": title,
                        "description": desc,
                        "deadline": deadline,
                        "priority": priority,
                        "checkpoints": cps,
                    },
                })
    random.shuffle(rows)
    return rows


def main() -> None:
    rows = gen()
    with OUT.open("w", encoding="utf-8") as fh:
        for r in rows:
            fh.write(json.dumps(r, ensure_ascii=False) + "\n")
    print(f"Сгенерировано {len(rows)} сложных примеров → {OUT}")


if __name__ == "__main__":
    main()
